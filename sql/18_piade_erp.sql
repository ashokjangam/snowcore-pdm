   All ERP identities, stock, prices and euros are scenarios, not source facts.
   Every row is deterministically anchored to observed or derived PIADE data.
   Cause codes are anonymised; material names deliberately do not assert a
   component identity. No CoMoPI object is referenced.
   ========================================================================== */
