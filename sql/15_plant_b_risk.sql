   Target: whether the next machine-hour has PCT_DOWNTIME > 0.10.
   Model selection happened offline on two rolling-origin validation periods.
   This file fits only the selected ExtraTrees configuration on all rows before
   2021-12-01 and reports performance only on the untouched final blind period.

   Honest limits:
   - PIADE has five anonymised machines from one site; external validity is
     unknown.
   - Current-hour downtime is a legitimate predictor but makes the model partly
     a sophisticated persistence rule. Baseline metrics are therefore stored
     beside every model metric.
   - The selected model won this finite candidate search; it is not claimed to
     be globally optimal.
   - Scores are operational rankings, not causal failure probabilities.
   ========================================================================== */

