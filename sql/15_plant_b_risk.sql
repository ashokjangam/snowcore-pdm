import numpy as np
import pandas as pd
from sklearn.ensemble import ExtraTreesClassifier
from sklearn.metrics import average_precision_score, roc_auc_score

SEED = 20260925
FINAL_TEST_START = pd.Timestamp("2021-12-01")
NOT_FEATURES = {
    "ROW_ID","MACHINE_KEY","MACHINE_CODE","HOUR_TS","SPLIT_PART","DATA_ORIGIN",
    "LABEL_HEAVY_STOP","NEXT_HOUR_DOWNTIME","BASELINE_SCORE",
}

def exact_fraction(y, score, machine, hour, fraction=0.10):
    """Exactly ceil(n*fraction) rows; deterministic tie break, no inflation."""
    order = pd.DataFrame({
        "score": np.asarray(score, dtype=float),
        "machine": machine.astype(str).to_numpy(),
        "hour": pd.to_datetime(hour).astype("int64").to_numpy(),
        "position": np.arange(len(y)),
    }).sort_values(
        ["score","machine","hour"], ascending=[False,True,True], kind="mergesort"
    )["position"].to_numpy()
    take = max(1, int(np.ceil(len(order) * fraction)))
    selected = order[:take]
    yy = np.asarray(y, dtype=int)
    hits = int(yy[selected].sum())
    return selected, hits / take, hits / int(yy.sum()) if yy.sum() else 0.0

def safe_metrics(y, score):
    if pd.Series(y).nunique() < 2:
        return None, None
    return float(roc_auc_score(y, score)), float(average_precision_score(y, score))

def run(session):
    df = session.table("ML.PLANT_B_FEATURES").to_pandas()
    df = df.sort_values(["MACHINE_CODE","HOUR_TS"], kind="mergesort").reset_index(drop=True)
    # Preserve the exact feature order used by the offline search. ExtraTrees
    # samples feature indices, so merely having the same set in another order
    # is not sufficient for a reproducible selected model.
    derived = ["RUN_FRAC","ALARM_TOTAL","ALARM_DISTINCT","TRANSITION_TOTAL"]
    history = []
    for source in [
        "PCT_DOWNTIME","PCT_IDLE","RUN_FRAC","ALARM_TOTAL",
        "ALARM_DISTINCT","STATE_CHANGES","COUNT_SUM",
    ]:
        for window in (3,6,12,24,72):
            history.append(f"{source}_MEAN_{window}")
            if window in (12,24,72):
                history.extend([f"{source}_MAX_{window}",f"{source}_STD_{window}"])
        history.extend([f"{source}_LAG_{lag}" for lag in (1,2,3,6,12,24)])
    extras = [
        "DOWNTIME_ACCEL_3_24","RUN_ACCEL_3_24","ALARM_ACCEL_3_24",
        "HOURS_SINCE_HEAVY_STOP","GAP_HOURS",
        "HOUR_SIN","HOUR_COS","DOW_SIN","DOW_COS",
        "MACHINE_S_1","MACHINE_S_2","MACHINE_S_3","MACHINE_S_4","MACHINE_S_5",
    ]
    engineered = set(derived + history + extras)
    source = [c for c in df.columns if c not in NOT_FEATURES
              and c not in engineered and pd.api.types.is_numeric_dtype(df[c])]
    features = source + derived + history + extras
    if len(features) != 299:
        raise ValueError(f"Feature contract drift: expected 299 numeric features, got {len(features)}")
    df[features] = df[features].replace([np.inf,-np.inf], np.nan).fillna(0)
    train = df[df["HOUR_TS"] < FINAL_TEST_START]
    test = df[df["HOUR_TS"] >= FINAL_TEST_START].copy()
    if train.empty or test.empty:
        raise ValueError("Chronological train/final-blind-test split produced an empty partition")

    model = ExtraTreesClassifier(
        n_estimators=700, max_features=0.4, min_samples_leaf=30,
        class_weight="balanced", n_jobs=-1, random_state=SEED,
    )
    model.fit(train[features], train["LABEL_HEAVY_STOP"].astype(int))
    test["RISK_SCORE"] = model.predict_proba(test[features])[:, 1]

    chosen, _, _ = exact_fraction(
        test["LABEL_HEAVY_STOP"], test["RISK_SCORE"],
        test["MACHINE_CODE"], test["HOUR_TS"])
    test["IS_FLAGGED"] = 0
    test.iloc[chosen, test.columns.get_loc("IS_FLAGGED")] = 1
    # Equal-workload rank bands remain meaningful if raw probabilities shift.
    rank = test[["RISK_SCORE","MACHINE_CODE","HOUR_TS"]].sort_values(
        ["RISK_SCORE","MACHINE_CODE","HOUR_TS"],
        ascending=[True,True,True], kind="mergesort").index
    percentile = pd.Series(np.arange(1, len(test)+1) / len(test), index=rank)
    test["RISK_PERCENTILE"] = test.index.map(percentile)
    test["RISK_BAND"] = pd.cut(
        test["RISK_PERCENTILE"], bins=[0,0.25,0.50,0.75,1.0],
        labels=["LOW","MODERATE","ELEVATED","HIGH"], include_lowest=True).astype(str)

    score_cols = [
        "ROW_ID","MACHINE_KEY","MACHINE_CODE","HOUR_TS","RISK_SCORE",
        "RISK_PERCENTILE","RISK_BAND","IS_FLAGGED","BASELINE_SCORE",
        "LABEL_HEAVY_STOP","NEXT_HOUR_DOWNTIME",
    ]
    scores = test[score_cols].copy()
    scores["SCORE_PERIOD"] = "FINAL_BLIND_TEST"
    scores["BLIND_TEST_START"] = FINAL_TEST_START
    scores["DATA_ORIGIN"] = "DERIVED_FROM_OBSERVED"
    session.write_pandas(scores, "PLANT_B_RISK_SCORE", schema="ML",
                         auto_create_table=True, overwrite=True, quote_identifiers=False)

    metric_rows = []
    for scope, grp in [("FLEET", test)] + list(test.groupby("MACHINE_CODE", sort=True)):
        y = grp["LABEL_HEAVY_STOP"].astype(int)
        model_auc, model_ap = safe_metrics(y, grp["RISK_SCORE"])
        base_auc, base_ap = safe_metrics(y, grp["BASELINE_SCORE"])
        _, mp, mr = exact_fraction(y, grp["RISK_SCORE"], grp["MACHINE_CODE"], grp["HOUR_TS"])
        _, bp, br = exact_fraction(y, grp["BASELINE_SCORE"], grp["MACHINE_CODE"], grp["HOUR_TS"])
        metric_rows.append({
            "SCOPE": scope, "TEST_ROWS": int(len(grp)), "BASE_RATE": float(y.mean()),
            "AUC": model_auc, "AVG_PRECISION": model_ap,
            "TOP_DECILE_PRECISION": mp, "TOP_DECILE_RECALL": mr,
            "BASELINE_AUC": base_auc, "BASELINE_AVG_PRECISION": base_ap,
            "BASELINE_TOP_DECILE_PRECISION": bp,
            "BASELINE_TOP_DECILE_RECALL": br,
            "TOP_DECILE_ROWS": int(np.ceil(len(grp)*0.10)),
        })
    metrics = pd.DataFrame(metric_rows)
    metrics["TRAIN_ROWS"] = int(len(train))
    metrics["FEATURE_COUNT"] = len(features)
    metrics["TARGET"] = "next machine-hour PCT_DOWNTIME > 0.10"
    metrics["MODEL"] = "sklearn ExtraTreesClassifier"
    metrics["MODEL_CONFIG"] = "n_estimators=700,max_features=0.4,min_samples_leaf=30,class_weight=balanced"
    metrics["SELECTION_METHOD"] = "offline rolling-origin search; final blind period excluded from selection"
    metrics["TRAIN_END_EXCLUSIVE"] = FINAL_TEST_START
    metrics["BLIND_TEST_START"] = FINAL_TEST_START
    metrics["BLIND_TEST_END"] = pd.to_datetime(test["HOUR_TS"]).max()
    metrics["SEED"] = SEED
    metrics["CAVEAT"] = "Single anonymised five-machine site; partly persistence; ranking is not causal and optimality is not claimed."
    metrics["TRAINED_AT"] = pd.Timestamp.utcnow().tz_localize(None)
    session.write_pandas(metrics, "PLANT_B_MODEL_METRICS", schema="ML",
                         auto_create_table=True, overwrite=True, quote_identifiers=False)

    importance = pd.DataFrame({
        "FEATURE": features,
        "IMPORTANCE": model.feature_importances_.astype(float),
    }).sort_values(["IMPORTANCE","FEATURE"], ascending=[False,True]).reset_index(drop=True)
    importance["RANK"] = np.arange(1, len(importance)+1)
    importance["MODEL"] = "ExtraTreesClassifier"
    importance["BLIND_TEST_START"] = FINAL_TEST_START
    session.write_pandas(importance, "PLANT_B_FEATURE_IMPORTANCE", schema="ML",
                         auto_create_table=True, overwrite=True, quote_identifiers=False)

    calibration = test.groupby("RISK_BAND", observed=True).agg(
        HOURS=("ROW_ID","size"), MEAN_SCORE=("RISK_SCORE","mean"),
        MIN_SCORE=("RISK_SCORE","min"), MAX_SCORE=("RISK_SCORE","max"),
        ACTUAL_RATE=("LABEL_HEAVY_STOP","mean"),
    ).reset_index()
    calibration["BANDING_METHOD"] = "final-blind-test score rank quartiles"
    session.write_pandas(calibration, "PLANT_B_CALIBRATION_BAND", schema="ML",
                         auto_create_table=True, overwrite=True, quote_identifiers=False)
    return {
        "model": "extra_leaf30_mf04", "features": len(features),
        "train_rows": int(len(train)), "blind_test_rows": int(len(test)),
        "blind_test_start": str(FINAL_TEST_START.date()),
        "scores_are_blind_test_only": True,
    }
